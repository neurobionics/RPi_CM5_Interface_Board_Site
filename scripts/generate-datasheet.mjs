import { readFile, writeFile, mkdir, access } from "node:fs/promises";
import { constants } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dataPath = path.join(rootDir, "data", "datasheet.json");
const srcAssetsDir = path.join(rootDir, "src", "assets");
const generatedSrcDir = path.join(rootDir, "src", "generated");
const generatedLatexDir = path.join(rootDir, "latex", "generated");
const generatedJsPath = path.join(generatedSrcDir, "datasheet.js");
const generatedLatexPath = path.join(generatedLatexDir, "datasheet.tex");
const requireCurrentPdf = process.argv.includes("--require-current-pdf");

const versionPattern = /^\d+\.\d+\.\d+$/;

const readJson = async (filePath) => JSON.parse(await readFile(filePath, "utf8"));

const fileExists = async (filePath) => {
  try {
    await access(filePath, constants.F_OK);
    return true;
  } catch {
    return false;
  }
};

const pdfFileName = (version) => `v${version}.pdf`;

const formatVoltage = (voltage) => (
  voltage.max !== undefined
    ? `${voltage.min}${voltage.unit || "V"} -- ${voltage.max}${voltage.unit || "V"}`
    : `${voltage.value}${voltage.unit || "V"}`
);

const validateData = (data) => {
  if (!data || typeof data !== "object") {
    throw new Error("datasheet.json must contain an object");
  }

  if (!versionPattern.test(data.currentVersion)) {
    throw new Error("currentVersion must use semantic version format, e.g. 1.1.1");
  }

  if (!Array.isArray(data.releases) || data.releases.length === 0) {
    throw new Error("releases must be a non-empty array");
  }

  const versions = data.releases.map((release) => release.version);
  if (versions.some((version) => !versionPattern.test(version))) {
    throw new Error("every release version must use semantic version format, e.g. 1.1.1");
  }

  if (new Set(versions).size !== versions.length) {
    throw new Error("release versions must be unique");
  }

  if (versions[0] !== data.currentVersion) {
    throw new Error("the first release must match currentVersion");
  }

  for (const release of data.releases) {
    if (!release.releaseDate) {
      throw new Error(`release ${release.version} is missing releaseDate`);
    }

    const changeLists = [release.newFeatures, release.changes, release.fixes];
    if (changeLists.every((list) => !Array.isArray(list) || list.length === 0)) {
      throw new Error(`release ${release.version} must contain at least one change`);
    }
  }
};

const validatePdfAssets = async (data) => {
  const missingHistoricalPdfs = [];
  const missingCurrentPdf = [];

  for (const release of data.releases) {
    const filePath = path.join(srcAssetsDir, pdfFileName(release.version));
    if (await fileExists(filePath)) {
      continue;
    }

    if (release.version === data.currentVersion) {
      missingCurrentPdf.push(pdfFileName(release.version));
    } else {
      missingHistoricalPdfs.push(pdfFileName(release.version));
    }
  }

  if (missingHistoricalPdfs.length > 0) {
    throw new Error(`Missing historical datasheet PDF(s): ${missingHistoricalPdfs.join(", ")}`);
  }

  if (requireCurrentPdf && missingCurrentPdf.length > 0) {
    throw new Error(`Missing current datasheet PDF: ${missingCurrentPdf[0]}`);
  }

  if (missingCurrentPdf.length > 0) {
    console.warn(`Current PDF is not present yet: ${missingCurrentPdf[0]}. The PDF build will create it.`);
  }

  return { missingCurrentPdf };
};

const jsString = (value) => JSON.stringify(value, null, 2);

const generateReactModule = (data, availableVersions) => {
  const imports = availableVersions.map((version, index) => (
    `import pdf${index} from "../assets/${pdfFileName(version)}";`
  ));
  const assetEntries = availableVersions.map((version, index) => (
    `  "${version}": pdf${index}`
  ));

  return `// This file is generated by scripts/generate-datasheet.mjs. Do not edit it manually.
${imports.join("\n")}

const datasheet = ${jsString(data)};

export const datasheetPdfAssets = {
${assetEntries.join(",\n")}
};

export default datasheet;
`;
};

const texEscape = (value) => String(value)
  .replaceAll("\\", "\\textbackslash{}")
  .replaceAll("{", "\\{")
  .replaceAll("}", "\\}")
  .replaceAll("%", "\\%")
  .replaceAll("&", "\\&")
  .replaceAll("#", "\\#")
  .replaceAll("_", "\\_")
  .replaceAll("$", "\\$")
  .replaceAll("~", "\\textasciitilde{}")
  .replaceAll("^", "\\textasciicircum{}");

const renderItems = (items, label) => {
  if (!Array.isArray(items) || items.length === 0) return "";
  return `
        \\textbf{${texEscape(label)}:}
        \\begin{itemize}[leftmargin=*, nosep]
${items.map((item) => `            \\item ${texEscape(item)}`).join("\n")}
        \\end{itemize}`;
};

const renderPinout = (pinout) => `
    \\subsection*{${texEscape(pinout.title)}}
    \\begin{minipage}[t]{0.60\\textwidth}
        \\begin{tabularx}{\\textwidth}{c X}
        \\toprule
        \\textbf{Pin} & \\textbf{Function} \\\\
        \\midrule
${pinout.pins.map(([pin, functionName]) => `        ${texEscape(pin)} & ${texEscape(functionName)} \\\\`).join("\n")}
        \\bottomrule
        \\end{tabularx}
    \\end{minipage}%
    \\hfill
    \\begin{minipage}[t]{0.35\\textwidth}
        \\centering
        \\includegraphics[width=\\linewidth]{${pinout.imageAsset}}
    \\end{minipage}

    \\vspace{0.6cm}`;

const renderRelease = (release) => `
    \\subsection*{v${texEscape(release.version)} -- ${texEscape(release.releaseDate)}}
${renderItems(release.newFeatures, "New Features")}
${renderItems(release.changes, "Changes")}
${renderItems(release.fixes, "Fixes")}`;

const generateLatexBody = (data) => {
  const leftPinouts = data.pinouts.slice(0, Math.ceil(data.pinouts.length / 2));
  const rightPinouts = data.pinouts.slice(Math.ceil(data.pinouts.length / 2));
  const technicalRows = data.technicalSpecifications
    .map((spec) => `    \\textbf{${texEscape(spec.category)}} & ${texEscape(spec.value)} \\\\`)
    .join("\n");
  const powerRows = [
    {
      category: "Input Voltage",
      value: data.power.inputs
        .map((input) => `${formatVoltage(input.voltage)} (${input.connector})`)
        .join(" | "),
    },
    {
      category: "Power Output",
      value: data.power.outputs
        .map((output) => `${output.voltage}V @ ${output.current}A (${output.type})`)
        .join(" | "),
    },
  ]
    .map((spec) => `    \\textbf{${texEscape(spec.category)}} & ${texEscape(spec.value)} \\\\`)
    .join("\n");
  const releaseHistory = data.releases.map(renderRelease).join("\n");
  const otherComponents = data.otherComponents
    .map((item) => `    \\item \\textbf{${texEscape(item.label)}:} ${texEscape(item.description)}`)
    .join("\n");
  const featureList = data.features
    .map((feature) => `            \\item ${texEscape(feature.datasheetTitle || feature.title)}`)
    .join("\n");
  const pinoutLeft = leftPinouts.map(renderPinout).join("\n");
  const pinoutRight = rightPinouts.map(renderPinout).join("\n");
  const dimensions = data.mechanical;

  return `
% Generated from data/datasheet.json. Do not edit this file manually.
\\newcommand{\\DatasheetVersion}{${texEscape(data.currentVersion)}}
\\newcommand{\\DatasheetVersionLabel}{v${texEscape(data.currentVersion)}}
\\newcommand{\\DatasheetBody}{%
\\enlargethispage{18pt}
% --- TITLE HEADER ---
\\begin{figure}[h!]
    \\begin{minipage}[c]{0.55\\textwidth}
        \\raggedright
        {\\color{brandblue}\\Huge \\textbf{RPi CM5 Interface Board}} \\\\[0.2cm]
        {\\Large Breakout board for the Raspberry Pi Compute Module 5} \\\\[0.15cm]
        {\\large \\textcolor{brandblue}{\\textbf{Board Version \\DatasheetVersion}}} \\\\[0.4cm]

        \\textbf{\\large Features}
        \\begin{itemize}[leftmargin=*, nosep]
${featureList}
        \\end{itemize}
    \\end{minipage}
    \\hfill
    \\begin{minipage}[c]{0.4\\textwidth}
        \\raggedleft
        \\includegraphics[width=0.95\\textwidth]{pcb-front.png}
    \\end{minipage}
\\end{figure}

% --- OVERVIEW ---
\\section{Overview}
${texEscape(data.overview)}

% --- TECHNICAL SPECS ---
\\section{Technical Specifications}
\\begin{table}[h!]
    \\centering
    \\renewcommand{\\arraystretch}{1.3}
    \\begin{tabularx}{\\textwidth}{l X}
    \\toprule
    \\textbf{Category} & \\textbf{Specification} \\\\
    \\midrule
${powerRows}
${technicalRows}
    \\bottomrule
    \\end{tabularx}
\\end{table}

% --- PINOUTS ---
\\section{Pinout \\& Interfaces}
\\begin{minipage}[t]{0.48\\textwidth}
${pinoutLeft}
\\end{minipage}
\\hfill
\\begin{minipage}[t]{0.48\\textwidth}
${pinoutRight}
\\end{minipage}

\\clearpage
% --- MECHANICAL ---
\\section{Mechanical Details}
\\begin{itemize}
    \\item \\textbf{PCB Dimensions:} $${texEscape(dimensions.lengthMm)}\\,\\si{mm} \\times ${texEscape(dimensions.widthMm)}\\,\\si{mm}$
    \\item \\textbf{Mounting Holes:} ${texEscape(dimensions.mountingHoles)}
    \\item \\textbf{Max Height:} $${texEscape(dimensions.maxHeightMm)}\\,\\si{mm}$ (${texEscape(dimensions.maxHeightDescription)})
\\end{itemize}

\\begin{figure}[h!]
    \\centering
    \\includegraphics[width=0.9\\textwidth]{mechanical_specs.png}
    \\caption{Mechanical Drawing \\& Sensor Origin}
\\end{figure}

% --- OTHER COMPONENTS ---
\\section{Other Components}
\\begin{itemize}[leftmargin=*]
${otherComponents}
\\end{itemize}

% --- REVISION HISTORY ---
\\section{Revision History}
${releaseHistory}
}
`;
};

const main = async () => {
  const data = await readJson(dataPath);
  validateData(data);
  const { missingCurrentPdf } = await validatePdfAssets(data);
  const availableVersions = data.releases
    .map((release) => release.version)
    .filter((version) => !missingCurrentPdf.includes(pdfFileName(version)));

  await mkdir(generatedSrcDir, { recursive: true });
  await mkdir(generatedLatexDir, { recursive: true });
  await writeFile(generatedJsPath, generateReactModule(data, availableVersions));
  await writeFile(generatedLatexPath, generateLatexBody(data));

  console.log(`Generated ${path.relative(rootDir, generatedJsPath)}`);
  console.log(`Generated ${path.relative(rootDir, generatedLatexPath)}`);
};

main().catch((error) => {
  console.error(`Datasheet generation failed: ${error.message}`);
  process.exitCode = 1;
});
